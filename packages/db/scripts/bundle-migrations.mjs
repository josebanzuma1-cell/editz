/**
 * Turns `migrations/*.sql` into a TypeScript module.
 *
 * The dev database has to apply migrations from inside a bundled Next.js
 * route, and a bundler cannot follow `new URL('../migrations/',
 * import.meta.url)` — it tries to resolve it as a module at build time and
 * fails. Reading the directory at runtime would also mean the files have to
 * exist next to the deployed output, which for a serverless target they do
 * not.
 *
 * So the SQL is compiled to data. `migrations.test.ts` fails if this file is
 * ever out of step with the directory, which is what makes the duplication
 * safe rather than a second source of truth.
 *
 * Run by `pnpm --filter @editz/db generate`, after drizzle-kit.
 */
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const migrationsDir = join(here, '..', 'migrations');
const target = join(here, '..', 'src', 'migrations.generated.ts');

const journal = JSON.parse(
  await readFile(join(migrationsDir, 'meta', '_journal.json'), 'utf8'),
);

const files = (await readdir(migrationsDir)).filter((name) => name.endsWith('.sql')).sort();

const entries = [];
for (const entry of journal.entries) {
  const name = `${entry.tag}.sql`;
  if (!files.includes(name)) throw new Error(`journal names ${name}, which is not there`);
  const sql = await readFile(join(migrationsDir, name), 'utf8');
  entries.push({ tag: entry.tag, sql });
}

const body = `/**
 * GENERATED by scripts/bundle-migrations.mjs. Do not edit.
 *
 * Run \`pnpm --filter @editz/db generate\` after changing the schema.
 */

export interface BundledMigration {
  tag: string;
  /** Statements, already split on drizzle's breakpoint marker. */
  statements: string[];
}

export const MIGRATIONS: readonly BundledMigration[] = ${JSON.stringify(
  entries.map((entry) => ({
    tag: entry.tag,
    statements: entry.sql
      .split('--> statement-breakpoint')
      .map((statement) => statement.trim())
      .filter(Boolean),
  })),
  null,
  2,
)};
`;

await writeFile(target, body, 'utf8');
console.log(`  bundled ${entries.length} migration(s) into src/migrations.generated.ts`);
